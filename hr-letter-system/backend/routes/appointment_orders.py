"""
appointment_orders.py
Routes:
  GET    /api/appointment-orders/               list (HR=all, employee/manager=own)
  GET    /api/appointment-orders/<id>           get single
  POST   /api/appointment-orders/               create draft from template + fields
  POST   /api/appointment-orders/<id>/submit    draft → pending_hr_head
  POST   /api/appointment-orders/<id>/hr-action HR Head approve / reject
  GET    /api/appointment-orders/<id>/download  download approved DOCX or PDF
  DELETE /api/appointment-orders/<id>           delete draft/rejected (admin/hr_head)

Lifecycle:  draft → pending_hr_head → approved / rejected
On approval: DOCX generated by replacing {{placeholders}} in template with
             the values the employee filled in.
All files stored in MongoDB GridFS — no local disk dependency.
"""

from flask import Blueprint, request, jsonify, current_app, send_file
from flask_jwt_extended import jwt_required, get_jwt_identity
from datetime import datetime
from bson import ObjectId
from io import BytesIO
import os, uuid, gridfs, tempfile

from services.letter_generator import generate_letter_docx, generate_letter_pdf

appointment_orders_bp = Blueprint('appointment_orders', __name__)

DELETABLE_STATUSES = {'draft', 'rejected'}


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def get_fs():
    return gridfs.GridFS(current_app.db, collection='files_fs')


def get_template_fs():
    return gridfs.GridFS(current_app.db, collection='templates_fs')


def _get_caller(db, uid):
    user = db.users.find_one({'_id': ObjectId(uid)})
    if not user:
        return None, (jsonify({'error': 'User not found'}), 404)
    return user, None


def _enrich(order, db):
    order['_id'] = str(order['_id'])
    try:
        emp = db.employees.find_one({'_id': ObjectId(order.get('employee_id', ''))})
        order['employee_name'] = emp.get('name', 'Unknown') if emp else 'Unknown'
        order['employee_code'] = emp.get('employee_id', '')  if emp else ''
    except Exception:
        order['employee_name'] = 'Unknown'
        order['employee_code'] = ''
    order.pop('docx_path', None)
    order.pop('pdf_path', None)
    return order


def _get_template_bytes(tmpl):
    """
    Get template file bytes from GridFS (new) or disk (legacy).
    Returns bytes or raises ValueError.
    """
    if tmpl.get('gridfs_id'):
        fs = get_template_fs()
        grid_out = fs.get(ObjectId(tmpl['gridfs_id']))
        return grid_out.read()
    elif tmpl.get('file_path') and os.path.exists(tmpl['file_path']):
        with open(tmpl['file_path'], 'rb') as f:
            return f.read()
    else:
        raise ValueError(f"Template '{tmpl.get('name')}' file not found. Please re-upload it.")


def _generate_docs_to_gridfs(tmpl, details, ref):
    """
    Generate DOCX (and PDF if possible) from template, save to GridFS.
    Returns (docx_gridfs_id, pdf_gridfs_id) — pdf may be None.
    """
    fs = get_fs()
    tmpl_bytes = _get_template_bytes(tmpl)

    with tempfile.TemporaryDirectory() as tmp:
        # Write template to temp dir
        tmpl_path = os.path.join(tmp, 'template.docx')
        with open(tmpl_path, 'wb') as f:
            f.write(tmpl_bytes)

        base      = ref.replace('/', '-').replace(' ', '_')
        docx_path = os.path.join(tmp, base + '.docx')
        pdf_path  = os.path.join(tmp, base + '.pdf')

        generate_letter_docx(tmpl_path, details, docx_path)

        # Save DOCX to GridFS
        with open(docx_path, 'rb') as f:
            docx_gid = str(fs.put(f.read(), filename=base + '.docx'))

        # Try PDF
        pdf_gid = None
        pdf_result = generate_letter_pdf(docx_path, pdf_path)
        if pdf_result and os.path.exists(pdf_result):
            with open(pdf_result, 'rb') as f:
                pdf_gid = str(fs.put(f.read(), filename=base + '.pdf'))

    return docx_gid, pdf_gid


