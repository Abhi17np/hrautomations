@appointment_orders_bp.route('/', methods=['GET'])
@jwt_required()
def list_orders():
    db  = current_app.db
    uid = get_jwt_identity()
    caller, err = _get_caller(db, uid)
    if err: return err

    query = {}
    if caller.get('role') in ('employee', 'manager'):
        emp_ref = caller.get('employee_ref', '')
        query['employee_id'] = emp_ref
    else:
        filter_emp_id = request.args.get('employee_id')
        if filter_emp_id:
            query['employee_id'] = filter_emp_id

    status = request.args.get('status')
    if status:
        query['status'] = status

    orders = list(db.appointment_orders.find(query).sort('created_at', -1))
    return jsonify([_enrich(o, db) for o in orders])


@appointment_orders_bp.route('/preview-template', methods=['POST'])
@jwt_required()
def preview_template():
    db          = current_app.db
    data        = request.json or {}
    template_id = data.get('template_id')
    fields      = data.get('fields', {})

    tmpl = db.templates.find_one({'_id': ObjectId(template_id)})
    if not tmpl:
        return jsonify({'error': 'Template not found'}), 404

    try:
        tmpl_bytes = _get_template_bytes(tmpl)
    except ValueError as e:
        return jsonify({'error': str(e)}), 404

    with tempfile.TemporaryDirectory() as tmp:
        tmpl_path = os.path.join(tmp, 'template.docx')
        with open(tmpl_path, 'wb') as f:
            f.write(tmpl_bytes)

        base      = f"preview_temp_{uuid.uuid4().hex}"
        docx_path = os.path.join(tmp, base + '.docx')
        pdf_path  = os.path.join(tmp, base + '.pdf')

        try:
            generate_letter_docx(tmpl_path, fields, docx_path)
        except Exception as e:
            return jsonify({'error': f'Preview failed: {e}'}), 500

        pdf_result = generate_letter_pdf(docx_path, pdf_path)

        if pdf_result and os.path.exists(pdf_result):
            with open(pdf_result, 'rb') as f:
                pdf_bytes = f.read()
            return send_file(BytesIO(pdf_bytes), mimetype='application/pdf')
        elif os.path.exists(docx_path):
            with open(docx_path, 'rb') as f:
                docx_bytes = f.read()
            return send_file(
                BytesIO(docx_bytes),
                mimetype='application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                as_attachment=True,
                download_name='preview.docx'
            )

    return jsonify({'error': 'Preview generation failed'}), 500


