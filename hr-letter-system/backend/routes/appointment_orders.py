@appointment_orders_bp.route('/', methods=['POST'])
@jwt_required()
def create_order():
    db  = current_app.db
    uid = get_jwt_identity()
    caller, err = _get_caller(db, uid)
    if err: return err

    data = request.json or {}

    if caller.get('role') not in ('hr', 'hr_head', 'admin'):
        return jsonify({'error': 'Only HR can create appointment orders'}), 403

    employee_id = data.get('employee_id', '')
    if not employee_id:
        return jsonify({'error': 'employee_id is required'}), 400

    emp = db.employees.find_one({'_id': ObjectId(employee_id)})
    if not emp:
        return jsonify({'error': 'Employee not found'}), 404

    existing = db.appointment_orders.count_documents({'employee_id': employee_id})
    ref_num  = f"AO-{emp.get('employee_id', 'EMP')}-{str(existing + 1).zfill(3)}"

    template_id = data.get('template_id')
    if not template_id:
        return jsonify({'error': 'template_id is required'}), 400
    tmpl = db.templates.find_one({'_id': ObjectId(template_id)})
    if not tmpl:
        return jsonify({'error': 'Template not found'}), 404

    fields = data.get('fields') or {}
    details = {
        **fields,
        'date':             datetime.now().strftime('%d-%m-%Y'),
        'reference_number': ref_num,
        'employee_id_code': emp.get('employee_id', ''),
    }

    doc = {
        'employee_id':      employee_id,
        'template_id':      template_id,
        'reference_number': ref_num,
        'status':           'draft',
        'details':          details,
        'approval_history': [],
        'created_by':       uid,
        'created_at':       datetime.utcnow(),
    }
    result = db.appointment_orders.insert_one(doc)
    return jsonify({'id': str(result.inserted_id), 'reference_number': ref_num}), 201


@appointment_orders_bp.route('/<oid>/submit', methods=['POST'])
@jwt_required()
def submit_order(oid):
    db  = current_app.db
    uid = get_jwt_identity()
    caller, err = _get_caller(db, uid)
    if err: return err
    if caller.get('role') not in ('hr', 'hr_head', 'admin'):
        return jsonify({'error': 'Only HR can submit appointment orders'}), 403
    o = db.appointment_orders.find_one({'_id': ObjectId(oid)})
    if not o:                  return jsonify({'error': 'Not found'}), 404
    if o['status'] != 'draft': return jsonify({'error': 'Only drafts can be submitted'}), 400

    db.appointment_orders.update_one({'_id': ObjectId(oid)}, {
        '$set':  {'status': 'pending_hr_head', 'updated_at': datetime.utcnow()},
        '$push': {'approval_history': {
            'user_id': uid, 'action': 'submitted',
            'from': 'draft', 'to': 'pending_hr_head',
            'timestamp': datetime.utcnow().isoformat(),
        }},
    })
    return jsonify({'message': 'Submitted to HR Head for approval'})


@appointment_orders_bp.route('/<oid>/update-fields', methods=['POST'])
@jwt_required()
def update_fields(oid):
    db  = current_app.db
    uid = get_jwt_identity()
    caller = db.users.find_one({'_id': ObjectId(uid)})
    if not caller:
        return jsonify({'error': 'User not found'}), 404
    if caller.get('role') not in ('hr', 'hr_head', 'admin'):
        return jsonify({'error': 'Only HR can edit appointment orders'}), 403

    o = db.appointment_orders.find_one({'_id': ObjectId(oid)})
    if not o: return jsonify({'error': 'Not found'}), 404
    if o['status'] != 'rejected':
        return jsonify({'error': 'Only rejected orders can be edited'}), 400

    data   = request.json or {}
    fields = data.get('fields', {})
    if not fields:
        return jsonify({'error': 'No fields provided'}), 400

    merged = {**o.get('details', {}), **fields}

    db.appointment_orders.update_one({'_id': ObjectId(oid)}, {
        '$set': {
            'details':    merged,
            'fields':     fields,
            'status':     'draft',
            'updated_at': datetime.utcnow(),
        },
        '$push': {'approval_history': {
            'user_id':   uid, 'action': 'edited_after_rejection',
            'from': 'rejected', 'to': 'draft',
            'timestamp': datetime.utcnow().isoformat(),
        }},
    })
    return jsonify({'message': 'Fields updated. Order is now a draft — ready to resubmit.'})


