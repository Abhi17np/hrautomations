@appointment_orders_bp.route('/<oid>/hr-action', methods=['POST'])
@jwt_required()
def hr_action(oid):
    db  = current_app.db
    uid = get_jwt_identity()
    caller, err = _get_caller(db, uid)
    if err: return err
    if caller.get('role') not in ('hr_head', 'admin'):
        return jsonify({'error': 'Only HR Head or Admin can approve appointment orders'}), 403

    o = db.appointment_orders.find_one({'_id': ObjectId(oid)})
    if not o: return jsonify({'error': 'Not found'}), 404
    if o['status'] != 'pending_hr_head':
        return jsonify({'error': f"Status is '{o['status']}', expected pending_hr_head"}), 400

    data    = request.json or {}
    act     = data.get('action')
    remarks = data.get('remarks', '').strip()

    if act not in ('approve', 'reject'):
        return jsonify({'error': "action must be 'approve' or 'reject'"}), 400
    if act == 'reject' and not remarks:
        return jsonify({'error': 'Rejection reason is required'}), 400

    new_status = 'approved' if act == 'approve' else 'rejected'

    update_ops = {
        '$set':  {'status': new_status, 'updated_at': datetime.utcnow()},
        '$push': {'approval_history': {
            'user_id':   uid,
            'user_name': caller.get('name', ''),
            'role':      caller.get('role'),
            'action':    act,
            'from':      'pending_hr_head',
            'to':        new_status,
            'remarks':   remarks,
            'timestamp': datetime.utcnow().isoformat(),
        }},
    }

    # ── On approval: generate DOCX/PDF and save to GridFS ──────────────────
    if act == 'approve':
        tmpl_id = o.get('template_id') or data.get('template_id')
        if tmpl_id:
            tmpl = db.templates.find_one({'_id': ObjectId(tmpl_id)})
        else:
            tmpl = db.templates.find_one({'type': 'appointment_order', 'is_active': True})

        if tmpl:
            details = dict(o.get('details', {}))
            details['approval_date'] = datetime.now().strftime('%d-%m-%Y')
            ref = o.get('reference_number', str(oid))

            try:
                docx_gid, pdf_gid = _generate_docs_to_gridfs(tmpl, details, ref)
                update_ops['$set']['docx_gridfs_id'] = docx_gid
                update_ops['$set']['pdf_gridfs_id']  = pdf_gid
                update_ops['$set']['template_id']    = str(tmpl['_id'])
            except Exception as e:
                import logging
                logging.getLogger(__name__).warning(f'AO doc generation failed: {e}')
        else:
            import logging
            logging.getLogger(__name__).warning('AO approval: no template found')

    update_ops['$set']['employee_notified'] = False
    db.appointment_orders.update_one({'_id': ObjectId(oid)}, update_ops)
    return jsonify({'message': f'Appointment order {act}d', 'new_status': new_status})


@appointment_orders_bp.route('/<oid>/download', methods=['GET'])
@jwt_required()
def download(oid):
    db  = current_app.db
    uid = get_jwt_identity()
    caller, err = _get_caller(db, uid)
    if err: return err

    fmt = request.args.get('format', 'pdf')
    o   = db.appointment_orders.find_one({'_id': ObjectId(oid)})
    if not o: return jsonify({'error': 'Not found'}), 404
    if o.get('status') != 'approved':
        return jsonify({'error': 'Appointment order must be approved before downloading'}), 400

    if caller.get('role') in ('employee', 'manager'):
        if o.get('employee_id') != caller.get('employee_ref', ''):
            return jsonify({'error': 'Access denied'}), 403

    ref = o.get('reference_number', 'AO')
    fs  = get_fs()

    # Try GridFS first
    if fmt == 'pdf' and o.get('pdf_gridfs_id'):
        try:
            grid_out = fs.get(ObjectId(o['pdf_gridfs_id']))
            return send_file(BytesIO(grid_out.read()), as_attachment=True,
                             download_name=f"{ref}.pdf", mimetype='application/pdf')
        except Exception:
            pass

    if o.get('docx_gridfs_id'):
        try:
            grid_out = fs.get(ObjectId(o['docx_gridfs_id']))
            return send_file(BytesIO(grid_out.read()), as_attachment=True,
                             download_name=f"{ref}.docx",
                             mimetype='application/vnd.openxmlformats-officedocument.wordprocessingml.document')
        except Exception:
            pass

    # Legacy fallback: disk paths
    if fmt == 'pdf' and o.get('pdf_path') and os.path.exists(o['pdf_path']):
        return send_file(o['pdf_path'], as_attachment=True, download_name=f"{ref}.pdf")
    if o.get('docx_path') and os.path.exists(o['docx_path']):
        return send_file(o['docx_path'], as_attachment=True, download_name=f"{ref}.docx")

    return jsonify({'error': 'Generated file not found. Try re-approving.'}), 404


